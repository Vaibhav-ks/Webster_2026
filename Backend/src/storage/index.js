// Storage drivers for original videos.
//
// The project service never talks to a storage SDK directly. It talks to a driver,
// chosen with STORAGE_DRIVER, that implements this interface:
//
//   kind        's3' | 'cloudinary'
//   store       stable id of the configured store, e.g. "s3:abc.r2.cloudflarestorage.com/videos"
//               or "cloudinary:my-cloud". Saved on every asset, so the server knows which
//               store each original lives in even after you switch providers.
//   bucket      bucket / container name recorded on the asset row (informational)
//   maxBytes    provider-side size limit, or null (the global MAX_UPLOAD_BYTES also applies)
//
//   begin(asset, state, { reupload })        -> { state, plan }
//       Start or resume an upload. `state` is persisted (source_assets.upload_state);
//       `plan` is sent to the browser and tells it which protocol to speak:
//         { protocol: 's3-multipart', partSize, partCount, uploadedParts }
//         { protocol: 'cloudinary-chunked', url, chunkSize, uploadId, fields }
//   signParts(asset, state, partNumbers)     -> [{ partNumber, url }]       (s3-multipart only)
//   finish(asset, state, report)             -> { ok: true, meta? }
//                                             | { ok: false, error, failed?, clearState? }
//       Verify the upload really completed and matches the expected size. `meta` is
//       persisted (source_assets.provider_meta) and handed back to later calls.
//   abort(asset, state)                      cancel an in-progress upload (best effort)
//   head(asset)                              -> { size } | null when the object is missing
//   downloadUrl(asset, { ttl })              -> short-lived URL the browser can GET
//   openStream(asset)                        -> { body, size, contentType } for the API to
//                                               stream the file itself (fallback when the
//                                               browser can't fetch the provider directly)
//   remove(asset)                            delete the object (missing is not an error)
//
// `asset` is { id, objectKey, mimeType, sizeBytes, filename, meta }. Object keys are
// generated by the server (u/<user>/p/<project>/source/<asset>) and never contain the
// user's file name. Keys are the same across providers.

import { createS3Storage } from './s3.js';
import { createCloudinaryStorage } from './cloudinary.js';

export function createStorage(storageConfig) {
  switch (storageConfig.driver) {
    case 's3':
      return createS3Storage(storageConfig.s3);
    case 'cloudinary':
      return createCloudinaryStorage(storageConfig.cloudinary);
    case 'none':
      return null;
    default:
      throw new Error(`Unknown STORAGE_DRIVER "${storageConfig.driver}" (use s3, cloudinary or none)`);
  }
}

/** Plain asset view handed to drivers, built from a source_assets row (or a joined row). */
export function assetView(row) {
  return {
    id: row.a_id ?? row.id,
    objectKey: row.object_key,
    mimeType: row.mime_type,
    sizeBytes: Number(row.size_bytes),
    filename: row.original_filename,
    meta: row.provider_meta ?? null,
  };
}
